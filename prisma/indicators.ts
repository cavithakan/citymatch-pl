/**
 * The indicator catalogue.
 *
 * Every metric the app can show or score is defined here and seeded into the
 * `Indicator` table. Nothing downstream — the refresh script, the scoring
 * engine, the city page — hardcodes a metric; they all read this table. Adding
 * a metric means adding a row here and re-running the seed and refresh.
 *
 * `availableAtDistrict` was established empirically: the nine city-level
 * indicators GUS does not publish per dzielnica are marked false so the Warsaw
 * district panel can render them as "not published at district level" instead
 * of quietly omitting them.
 */

