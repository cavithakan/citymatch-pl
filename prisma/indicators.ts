  /** English equivalent shown in the English interface. */
  unitEn: string;
  labelPl: string;
  labelEn: string;
  descPl?: string;
  descEn?: string;
  availableAtDistrict: boolean;
  /** Omit to treat a stored zero as "not published". See schema.prisma. */
